"""Step 9 | Core pipeline: routing, retrieval, deterministic 'why' explanations, LLM intro, session memory and contract output."""
from read import load_movies
from clean import clean_movies
from decided import decide
from search import find_movies
from prompts import build_messages
import time
import re
import llm

MOVIES = clean_movies(load_movies())

MOOD_FA = {"happy": "شاد", "sad": "غمگین", "angry": "عصبانی", "surprise": "متعجب", "neutral": "خنثی"}
GENRE_FA = {
    "animation": "انیمیشن", "comedy": "کمدی", "drama": "درام", "family": "خانوادگی",
    "adventure": "ماجراجویی", "sci-fi": "علمی‌تخیلی", "action": "اکشن", "thriller": "تریلر",
    "romance": "عاشقانه", "fantasy": "فانتزی", "mystery": "معمایی", "music": "موزیکال",
    "crime": "جنایی", "war": "جنگی", "horror": "ترسناک", "documentary": "مستند", "history": "تاریخی",
}
OFFLINE_TEXT = ("الان به مدل زبانی وصل نیستم. حالت رو با یکی از کلمه‌های شاد، غمگین، عصبانی، "
                "هیجان‌زده یا معمولی بگو تا فیلم پیدا کنم.")


def new_session():
    """Create an empty per-user session (history and last constraints)."""
    return {"history": [], "last_moods": [], "last_genres": [], "last_exclude": [], "shown": []}


def explain(m, moods, genres, exclude=()):
    """Build the 'why' sentence for a movie from dataset fields only; it is never generated by the LLM."""
    parts = []
    hit_moods = [MOOD_FA[x] for x in m["moods"] if x in moods]
    hit_genres = [GENRE_FA.get(x, x) for x in m["genres"] if x in genres]
    if hit_moods:
        parts.append(f"برچسب حالش «{'، '.join(hit_moods)}» هست و با حال تو می‌خونه")
    if hit_genres:
        parts.append(f"ژانر {'، '.join(hit_genres)} هم دقیقاً همونیه که خواستی")
    if not hit_genres:
        parts.append("ژانرش " + "، ".join(GENRE_FA.get(x, x) for x in m["genres"]))
    if exclude:
        parts.append("و " + "، ".join(GENRE_FA.get(x) or MOOD_FA.get(x, x) for x in exclude) + " نیست")
    parts.append(f"امتیازش {m['rating']} هست")
    return "؛ ".join(parts)


def format_movies(candidates, moods, genres, exclude=()):
    """Render the movie list with one explanation per movie."""
    lines = []
    for m in candidates:
        name = m["title_fa"] or m["title"]
        lines.append(f"• {name} ({m['year']}) — چرا: {explain(m, moods, genres, exclude)}")
    return "\n".join(lines)


def clean_intro(text, fallback):
    """Strip counts, questions and list-like content the LLM may add so the intro stays short."""
    text = (text or "").strip()
    for marker in ["•", "\n-", "\n*", "\n1.", "\n۱.", "["]:
        i = text.find(marker)
        if i != -1:
            text = text[:i]
    text = text.split("\n\n")[0].strip()
    if len(text) > 250:
        cut = max(text.rfind(p, 0, 250) for p in [".", "!", "؟", "…"])
        text = text[:cut + 1] if cut > 0 else text[:250]
    parts = re.split(r"(?<=[.!؟?…])\s+", text)
    count = re.compile(r"(یک|دو|سه|چهار|پنج|چند|\d+)\s*(تا|عدد)\s*(\S+\s+)?(فیلم|پیشنهاد|انیمیشن)")
    parts = [p for p in parts if not count.search(p)]
    statements = [p for p in parts if not p.rstrip().endswith(("؟", "?"))]
    text = " ".join(statements or parts).strip()
    return text or fallback


def _cards(candidates, moods=(), genres=(), exclude=()):
    """Movie fields sent to the UI, including the deterministic 'why' text."""
    return [{**{k: m[k] for k in ("id", "title", "title_fa", "year", "genres", "moods", "rating", "poster")},
             "why": explain(m, moods, genres, exclude)} for m in candidates]


def _prepare(user_text, session):
    """Phase 1: choose the route, search, and build the LLM messages."""
    d = decide(user_text, session)
    moods, genres, exclude = d["moods"], d["genres"], d["exclude"]
    candidates = []
    if d["route"] == "rag":
        if not d["more"]:
            session["shown"] = []
        candidates = find_movies(MOVIES, moods, genres, k=3,
                                 exclude_ids=session["shown"], exclude=exclude)
        session["last_moods"], session["last_genres"], session["last_exclude"] = moods, genres, exclude
        session["shown"] += [m["id"] for m in candidates]
        local = "با توجه به حالت، این فیلم‌ها رو پیشنهاد می‌کنم:"
    else:
        local = OFFLINE_TEXT
    return {"route": d["route"], "user_text": user_text, "candidates": candidates,
            "moods": moods, "genres": genres, "exclude": exclude, "local": local,
            "messages": build_messages(session["history"], user_text, candidates)}


def _finish(plan, llm_text, session):
    """Phase 2: assemble the final reply, update session memory and build the response."""
    candidates, moods = plan["candidates"], plan["moods"]
    if plan["route"] == "rag":
        intro = clean_intro(llm_text, plan["local"])
        reply = history_text = intro
        if candidates:
            reply += "\n\n" + format_movies(candidates, moods, plan["genres"], plan["exclude"])
            reply += "\n\nکدوم بیشتر به دلت نشست؟ یا بگو «یکی دیگه» تا فیلم‌های جدید بدم."
            names = "، ".join(m["title_fa"] or m["title"] for m in candidates)
            history_text = f"{intro} [فیلم‌های نشون داده‌شده: {names}]"
    else:
        reply = history_text = (llm_text or OFFLINE_TEXT).strip()

    session["history"] += [{"role": "user", "content": plan["user_text"]},
                           {"role": "assistant", "content": history_text}]
    return {
        "reply": reply,
        "mood": moods[0] if moods else "neutral",
        "movies": [m["id"] for m in candidates],
        "cards": _cards(candidates, moods, plan["genres"], plan["exclude"]),
        "route": plan["route"],
    }


def respond(user_text, session):
    """Synchronous response for one user message."""
    plan = _prepare(user_text, session)
    return _finish(plan, llm.chat(plan["messages"], plan["local"]), session)


def respond_stream(user_text, session):
    """Generator yielding meta, delta and done events for streaming UIs."""
    t0 = time.time()
    plan = _prepare(user_text, session)
    t_decide = time.time() - t0
    if plan["candidates"]:
        yield {"type": "meta", "cards": _cards(plan["candidates"], plan["moods"], plan["genres"], plan["exclude"]),
               "contract": {"mood": plan["moods"][0] if plan["moods"] else "neutral",
                            "movies": [m["id"] for m in plan["candidates"]]}}
    text = ""
    llm.LAST.clear()
    for piece in llm.chat_stream(plan["messages"], plan["local"]):
        text += piece
        yield {"type": "delta", "text": piece}
    result = _finish(plan, text, session)
    result["contract"] = contract_output(result)
    print(f"⏱ مسیر: {plan['route']} | تصمیم‌گیری: {t_decide:.1f} ثانیه | کل: {time.time() - t0:.1f} ثانیه")
    yield {"type": "done", **result}


def contract_output(result):
    """Return the shared-contract JSON: {"mood": ..., "movies": [ids]}."""
    return {"mood": result["mood"], "movies": result["movies"]}


if __name__ == "__main__":
    s = new_session()
    while True:
        text = input("تو: ")
        if text.strip() == "exit":
            break
        print("سینمو:", respond(text, s)["reply"], "\n")
